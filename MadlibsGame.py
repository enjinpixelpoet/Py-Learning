# Madlibs Game
# Word game where the user inputs words to fill in the blanks of a story.

adjective1 = input("Enter an adjective: ")
noun1 = input("Enter a noun: ")
verb1 = input("Enter a verb: ")
adjective2 = input("Enter another adjective: ")
noun2 = input("Enter another noun: ")
verb2 = input("Enter another verb: ")


print(f"Today I went to {adjective1} zoo.")
print(f"In an exhibit, I saw a {noun1}")
print(f"The {noun1} was {verb1}ing and it looked very {adjective2}.")
print(f"Then I saw a {noun2} that was {verb2}ing.")
